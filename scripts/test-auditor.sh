#!/usr/bin/env bash
# Offline test of deploy/auditor/render.sh (no cluster; python3 + PyYAML). Exit != 0 on any failure.
set -uo pipefail
cd "$(dirname "$0")/.."
R=deploy/auditor/render.sh
fails=0
fail() { echo "FAIL: $*" >&2; fails=$((fails + 1)); }
ok() { echo "ok:   $*"; }
T=$(mktemp -d); trap 'rm -r -- "$T"' EXIT
D=sha256:$(printf 'a%.0s' $(seq 1 64))
H64=$(printf '0123456789abcdef%.0s' 1 2 3 4)
P="$T/public"; mkdir "$P"
CHAIN=11111111-2222-4333-8444-555555555555
echo "$CHAIN" > "$P/chain_id"
printf 'hash:%s#ABCD\n' "${H64^^}" > "$P/genesis.expected_hash"
jq -n '[ "bi","bank-a","bank-b","bank-c" | {party: ., public_key: ("ea0130" + .), pop_hex: "0xaa"} ]' > "$P/peers.json"
jq -n '{bi:"ed0120aa","bank-a":"ed0120bb","bank-b":"ed0120cc","bank-c":"ed0120dd","bi-gov":"ed0120ee"}' > "$P/accounts.json"
H8=${H64:0:8}

refuse() { # <label> <expected message part> <args...>
  local label=$1 part=$2; shift 2
  local err rc
  err=$("$R" "$@" 2>&1 >/dev/null); rc=$?
  [[ $rc -eq 2 && $err == *"$part"* ]] && ok "refuses $label (exit 2)" || fail "$label not refused as expected (rc=$rc: $err)"
}
refuse "no arguments" "usage"
refuse "an unknown party" "usage" nobody "$D" "$P"
refuse "bank-c (no auditor in this step)" "usage" bank-c "$D" "$P"
refuse "a tag instead of a digest" "digest" bi "debian:latest" "$P"
refuse "a short digest" "digest" bi "sha256:abc" "$P"
refuse "a missing public dir" "public dir" bi "$D" "$T/none"
mkdir "$T/p2"; cp "$P/chain_id" "$P/peers.json" "$T/p2/"; refuse "a public dir without genesis.expected_hash" "genesis.expected_hash" bi "$D" "$T/p2"
mkdir "$T/p3"; cp "$P"/* "$T/p3/"; : > "$T/p3/x.seed"; refuse "a public dir holding a seed" "private material" bi "$D" "$T/p3"

for p in bi bank-a bank-b; do
  out=$("$R" "$p" "$D" "$P" 2>&1) || { fail "$p: render failed: $out"; continue; }
  grep -q '@[A-Z_]*@' <<<"$out" && fail "$p: unreplaced placeholder in output"
  python3 -I scripts/check-auditor.py "$p" "$D" "$H8" "$CHAIN" <<<"$out" || fails=$((fails + 1))
  python3 -I scripts/check-netpol-form.py "auditor" <<<"$out" || fails=$((fails + 1))
done
a=$("$R" bi "$D" "$P"); b=$("$R" bi "$D" "$P")
[[ $a == "$b" ]] && ok "render is deterministic" || fail "render differs between runs"
before=$(find "$T" -type f | sort | xargs cksum)
"$R" bi "$D" "$P" >/dev/null; [[ $(find "$T" -type f | sort | xargs cksum) == "$before" ]] && ok "writes nothing" || fail "files changed"
# --keys-in-pvc (3b option 4, orchestrator-approved): bank-a and bank-b only; the auditor key pair is generated by an initContainer into the audit-store PVC
refuse "--keys-in-pvc for bi (the BI auditor keeps the Secret model)" "keys-in-pvc" bi "$D" "$P" --keys-in-pvc
refuse "--keys-in-pvc for bank-c" "usage" bank-c "$D" "$P" --keys-in-pvc
refuse "an unknown fifth argument" "usage" bank-a "$D" "$P" --frob
for p in bank-a bank-b; do
  out=$("$R" "$p" "$D" "$P" --keys-in-pvc 2>&1) || { fail "$p --keys-in-pvc: render failed: $out"; continue; }
  python3 -I scripts/check-auditor.py "$p" "$D" "$H8" "$CHAIN" pvc <<<"$out" || fails=$((fails + 1))
  python3 -I scripts/check-netpol-form.py "auditor-pvc" <<<"$out" || fails=$((fails + 1))
  # the PLAIN checker must reject the PVC render (it expects the Secret model) and the PVC checker must reject the plain render
  python3 -I scripts/check-auditor.py "$p" "$D" "$H8" "$CHAIN" <<<"$out" >/dev/null 2>&1 && fail "$p: the Secret-model checker accepted a --keys-in-pvc render" || ok "$p: Secret-model checker rejects the PVC render"
  python3 -I scripts/check-auditor.py "$p" "$D" "$H8" "$CHAIN" pvc <<<"$("$R" "$p" "$D" "$P")" >/dev/null 2>&1 && fail "$p: the PVC checker accepted a plain render" || ok "$p: PVC checker rejects the plain render"
done
# --gw-tls (analyst ruling P1, auditors reach the 4 gateways ONLY): localhost mTLS envoy sidecar, egress DNS + 4 gateways :8443, NO Torii
mkdir -p "$P/gateway-ca"; for q in bi bank-a bank-b bank-c; do printf -- '-----BEGIN CERTIFICATE-----\nMIIB%s\n-----END CERTIFICATE-----\n' "$q" > "$P/gateway-ca/$q-server-ca.pem"; done
BC=203.0.113.44
refuse "--gw-tls without --bank-c-gw-cidr" "bank-c-gw-cidr" bi "$D" "$P" --gw-tls
refuse "--gw-tls with a private --bank-c-gw-cidr" "public" bi "$D" "$P" --gw-tls --bank-c-gw-cidr 10.0.0.1/32
refuse "--gw-tls with a wide --bank-c-gw-cidr" "/32" bi "$D" "$P" --gw-tls --bank-c-gw-cidr 203.0.113.0/24
refuse "--bank-c-gw-cidr without --gw-tls" "usage" bi "$D" "$P" --bank-c-gw-cidr $BC/32
mkdir "$T/p_ca"; cp "$P/chain_id" "$P/genesis.expected_hash" "$P/peers.json" "$P/accounts.json" "$T/p_ca/"; refuse "--gw-tls without the public server CAs" "server-ca" bi "$D" "$T/p_ca" --gw-tls --bank-c-gw-cidr $BC/32
for p in bi bank-a bank-b; do
  out=$("$R" "$p" "$D" "$P" --gw-tls --bank-c-gw-cidr $BC/32 2>&1) || { fail "$p --gw-tls: render failed: $out"; continue; }
  python3 -I scripts/check-auditor.py "$p" "$D" "$H8" "$CHAIN" gwtls bankc:$BC <<<"$out" || fails=$((fails + 1))
  python3 -I scripts/check-netpol-form.py "auditor-gwtls" <<<"$out" || fails=$((fails + 1))
done
out=$("$R" bank-a "$D" "$P" --keys-in-pvc --gw-tls --bank-c-gw-cidr $BC/32 2>&1) && python3 -I scripts/check-auditor.py bank-a "$D" "$H8" "$CHAIN" pvc gwtls bankc:$BC <<<"$out" || { fail "bank-a --keys-in-pvc + --gw-tls"; }
gw_out=$("$R" bank-a "$D" "$P" --gw-tls --bank-c-gw-cidr $BC/32)
gmut() { # <label> <python statement on docs (dict by (kind,name)) d>
  python3 -I -c '
import sys, yaml
docs = [x for x in yaml.safe_load_all(sys.stdin.read()) if x]
by = {(x["kind"], x["metadata"]["name"]): x for x in docs}
exec(sys.argv[1])
print(yaml.safe_dump_all(docs))' "$2" <<<"$gw_out" | python3 -I scripts/check-auditor.py bank-a "$D" "$H8" "$CHAIN" gwtls bankc:$BC >/dev/null 2>&1 && fail "MUTANT $1 passed" || ok "MUTANT: $1 FAILS the gw-tls checker"
}
EV='yaml.safe_load(by[("ConfigMap","auditor-gw-envoy")]["data"]["envoy.yaml"])'
gmut "a sidecar listener on 0.0.0.0" 'e = '"$EV"'; e["static_resources"]["listeners"][0]["address"]["socket_address"]["address"] = "0.0.0.0"; by[("ConfigMap","auditor-gw-envoy")]["data"]["envoy.yaml"] = yaml.safe_dump(e)'
gmut "an upstream with system roots (no trusted_ca)" 'e = '"$EV"'; e["static_resources"]["clusters"][0]["transport_socket"]["typed_config"]["common_tls_context"]["validation_context"].pop("trusted_ca"); by[("ConfigMap","auditor-gw-envoy")]["data"]["envoy.yaml"] = yaml.safe_dump(e)'
gmut "skip-verify (trust_chain_verification ACCEPT_UNTRUSTED)" 'e = '"$EV"'; e["static_resources"]["clusters"][1]["transport_socket"]["typed_config"]["common_tls_context"]["validation_context"]["trust_chain_verification"] = "ACCEPT_UNTRUSTED"; by[("ConfigMap","auditor-gw-envoy")]["data"]["envoy.yaml"] = yaml.safe_dump(e)'
gmut "no SAN match on an upstream" 'e = '"$EV"'; e["static_resources"]["clusters"][2]["transport_socket"]["typed_config"]["common_tls_context"]["validation_context"].pop("match_typed_subject_alt_names"); by[("ConfigMap","auditor-gw-envoy")]["data"]["envoy.yaml"] = yaml.safe_dump(e)'
gmut "an admin interface on the sidecar" 'e = '"$EV"'; e["admin"] = {"address": {"socket_address": {"address": "127.0.0.1", "port_value": 9901}}}; by[("ConfigMap","auditor-gw-envoy")]["data"]["envoy.yaml"] = yaml.safe_dump(e)'
gmut "Torii 8080 back in the auditor egress" 'by[("NetworkPolicy","auditor-egress")]["spec"]["egress"].append({"to": [{"podSelector": {"matchLabels": {"rd-iroha3/role": "peer", "rd-iroha3/party": "bank-a"}}}], "ports": [{"protocol": "TCP", "port": 8080}]})'
gmut "an extra ipBlock in the auditor egress" 'by[("NetworkPolicy","auditor-egress")]["spec"]["egress"][1]["to"].append({"ipBlock": {"cidr": "8.8.8.8/32"}})'
gmut "the client key mounted into the auditor container" 'by[("Deployment","auditor")]["spec"]["template"]["spec"]["containers"][0]["volumeMounts"].append({"name": "client-cert", "mountPath": "/client", "readOnly": True})'
gmut "the sidecar image by tag" 'by[("Deployment","auditor")]["spec"]["template"]["spec"]["containers"][1]["image"] = "envoyproxy/envoy:v1.30.0"'
gmut "a torii URL on a non-loopback host" 'import tomllib; t = by[("ConfigMap","auditor-config")]["data"]; t["rd-dfabi.toml"] = t["rd-dfabi.toml"].replace("http://127.0.0.1:18102/", "http://bank-a-0.bank-a.rd-iroha3-bank-a.svc.cluster.local:8080/")'
# MUTANTS of the --keys-in-pvc render: each must make the PVC checker FAIL
pvc_out=$("$R" bank-a "$D" "$P" --keys-in-pvc)
pmut() { # <label> <python statement on the Deployment pod spec dict ps>
  python3 -I -c '
import sys, yaml
docs = [x for x in yaml.safe_load_all(sys.stdin.read()) if x]
for d in docs:
    if d["kind"] == "Deployment": ps = d["spec"]["template"]["spec"]; exec(sys.argv[1])
print(yaml.safe_dump_all(docs))' "$2" <<<"$pvc_out" | python3 -I scripts/check-auditor.py bank-a "$D" "$H8" "$CHAIN" pvc >/dev/null 2>&1 && fail "MUTANT $1 passed" || ok "MUTANT: $1 FAILS the PVC checker"
}
pmut "a leftover key Secret volume" 'ps["volumes"].append({"name": "keys", "secret": {"secretName": "bank-a-auditor-key"}})'
pmut "the init script overwrites (rm of the key files)" 'ps["initContainers"][0]["command"][2] += "\nrm -f \"$s\""'
pmut "the init script prints the seed (cat)" 'ps["initContainers"][0]["command"][2] += "\ncat \"$s\""'
pmut "an env var on the init container" 'ps["initContainers"][0]["env"] = [{"name": "X", "value": "y"}]'
pmut "the init container with a service-account style extra mount" 'ps["initContainers"][0]["volumeMounts"].append({"name": "config", "mountPath": "/c"})'
pmut "the keys mount not read-only" 'ps["containers"][0]["volumeMounts"][0]["readOnly"] = False'
pmut "the half-pair guard removed" 'ps["initContainers"][0]["command"][2] = ps["initContainers"][0]["command"][2].replace("exit 1", "exit 0")'
# FUNCTIONAL test of the rendered init script with a STUB rd-dfabi (known secret bytes): public-only log, create-only, 0400, no overwrite, half pair fails
S0="$T/init.sh"
python3 -I -c '
import sys, yaml
docs = [x for x in yaml.safe_load_all(sys.stdin.read()) if x]
d = [x for x in docs if x["kind"] == "Deployment"][0]
open(sys.argv[1], "w").write(d["spec"]["template"]["spec"]["initContainers"][0]["command"][2])' "$S0" <<<"$("$R" bank-a "$D" "$P" --keys-in-pvc)"
ST="$T/state"; mkdir -p "$ST" "$T/stubbin"
cat > "$T/stubbin/rd-dfabi" <<'STUB'
#!/usr/bin/env bash
echo "$*" >> "$STUB_LOG"
case "$1 $2" in
  "keys new")        ( set -o noclobber; printf 'SECRETSEED_DEADBEEF' > "$3/$4.seed" ) || exit 1; chmod 600 "$3/$4.seed"; echo "$4 PUBKEY_ed0120abcdef" ;;
  "keys new-hybrid") [[ -n ${STUB_FAIL_HYBRID:-} ]] && { echo "stub failure" >&2; exit 1; }; ( set -o noclobber; printf 'SECRETHYBRID_CAFEBABE' > "$3/$4.hybrid" ) || exit 1; chmod 600 "$3/$4.hybrid"; echo "$3/$4.hybrid" ;;
  *) exit 2 ;;
esac
STUB
chmod +x "$T/stubbin/rd-dfabi"
sed -e "s|/usr/local/bin/rd-dfabi|$T/stubbin/rd-dfabi|g" -e "s|/state|$ST|g" "$S0" > "$T/init-run.sh"
export STUB_LOG="$T/stub.log"; : > "$STUB_LOG"
out=$(bash "$T/init-run.sh" 2>&1); rc=$?
K="$ST/keys/bank-a-auditor"
[[ $rc -eq 0 && -f $K.seed && -f $K.hybrid ]] && ok "init: creates the seed and the hybrid key when both are absent" || fail "init fresh: rc=$rc $out"
[[ $(stat -c %a "$K.seed") == 400 && $(stat -c %a "$K.hybrid") == 400 ]] && ok "init: both files are mode 0400" || fail "init: modes $(stat -c %a "$K.seed" "$K.hybrid" | tr '\n' ' ')"
[[ $out != *SECRET* && $out != *DEADBEEF* && $out != *CAFEBABE* ]] && ok "init: the log holds NO private bytes" || fail "init: private bytes in the log: $out"
[[ $out == *PUBKEY_ed0120abcdef* && $out == *"$(printf %s PUBKEY_ed0120abcdef | sha256sum | cut -d' ' -f1)"* ]] && ok "init: logs the PUBLIC key and its sha256" || fail "init: public key/sha missing: $out"
before=$(cksum "$K.seed" "$K.hybrid"; stat -c %Y "$K.seed" "$K.hybrid"); n0=$(wc -l < "$STUB_LOG")
out=$(bash "$T/init-run.sh" 2>&1); rc=$?
[[ $rc -eq 0 && $out == *"keys present"* && $(wc -l < "$STUB_LOG") == "$n0" ]] && ok "init: both present -> 'keys present', the generator is NOT called" || fail "init rerun: rc=$rc $out"
[[ $(cksum "$K.seed" "$K.hybrid"; stat -c %Y "$K.seed" "$K.hybrid") == "$before" ]] && ok "init: a rerun never overwrites (bytes and mtime unchanged)" || fail "init: rerun changed the key files"
[[ $out != *SECRET* ]] && ok "init: rerun log holds no private bytes" || fail "init rerun leaked"
chmod 600 "$K.hybrid"; rm -f "$K.hybrid"; n1=$(wc -l < "$STUB_LOG")
out=$(bash "$T/init-run.sh" 2>&1); rc=$?
[[ $rc -ne 0 && $(wc -l < "$STUB_LOG") == "$n1" && -f $K.seed && ! -e $K.hybrid ]] && ok "init: exactly one of the two files present -> FAIL, nothing generated, nothing completed" || fail "init half pair: rc=$rc $out"
find "$ST" -mindepth 1 -delete; : > "$STUB_LOG"
out=$(STUB_FAIL_HYBRID=1 bash "$T/init-run.sh" 2>&1); rc=$?
[[ $rc -ne 0 && $out != *SECRET* ]] && ok "init: a generator failure -> non-zero exit (pipefail/rc), no private bytes" || fail "init generator failure: rc=$rc $out"
out=$(bash "$T/init-run.sh" 2>&1); rc=$?
[[ $rc -ne 0 ]] && ok "init: after a partial failure the next run FAILS closed (half pair), it does not regenerate" || fail "init after partial: rc=$rc $out"
if (( fails )); then echo "FAILED: $fails check(s)" >&2; exit 1; fi
echo "PASS"
