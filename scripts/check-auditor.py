#!/usr/bin/env python3
"""Check rendered S11/S12 auditor manifests on stdin. Usage: check-auditor.py <party> <digest> <hash8> <chain-id> [pvc] [gwtls bankc:<ip>]
(pvc = rendered with --keys-in-pvc: the key pair is generated by an initContainer INTO the audit-store PVC, no key Secret)"""
import json
import sys
import tomllib

import yaml

party, digest, h8, chain = sys.argv[1:5]
pvcmode = "pvc" in sys.argv[5:]
gwtls = "gwtls" in sys.argv[5:]  # rendered with --gw-tls: localhost mTLS envoy sidecar `gw-tls` (analyst ruling P1); no Torii egress
bankc_ip = next((a.split(":", 1)[1] for a in sys.argv[5:] if a.startswith("bankc:")), "")
ns = f"rd-iroha3-{party}"
key_name = "bi-auditor" if party == "bi" else f"{party}-auditor"
docs = [d for d in yaml.safe_load_all(sys.stdin.read()) if d]
by = {(d["kind"], d["metadata"]["name"]): d for d in docs}
bad = []


def need(kind, name):
    d = by.get((kind, name))
    if d is None:
        bad.append(f"missing {kind} {name}")
    return d


want = {("ConfigMap", "auditor-config"), ("PersistentVolumeClaim", "audit-store"), ("Deployment", "auditor"), ("Service", "auditor"),
        ("NetworkPolicy", "auditor-ingress"), ("NetworkPolicy", "auditor-egress")}
if gwtls:
    want |= {("ConfigMap", "auditor-gw-envoy"), ("ConfigMap", "auditor-server-cas")}
if set(by) != want or len(docs) != len(want):
    bad.append(f"objects: want exactly {sorted(want)}, got {sorted(by)} ({len(docs)} documents)")
for (k, n), d in by.items():
    if d["metadata"].get("namespace") != ns:
        bad.append(f"{k} {n} is in namespace {d['metadata'].get('namespace')}, want {ns}")
    if d["metadata"].get("labels", {}).get("app.kubernetes.io/part-of") != "rd-iroha3":
        bad.append(f"{k} {n}: label part-of=rd-iroha3 missing")
if any(k == "Secret" for k, _ in by):
    bad.append("a Secret must never be rendered (the org creates its own auditor key Secret with its own kubeconfig)")
flat = json.dumps(docs)
for banned in ("nodeSelector", "nodeName", "affinity", "priorityClassName", "hostNetwork", "bi-auditor-key" if party != "bi" else "@@"):
    if banned in flat:
        bad.append(f"rendered objects must not contain {banned!r}")

cm = need("ConfigMap", "auditor-config")
if cm:
    if set(cm["data"]) != {"rd-dfabi.toml", "peers.json"}:
        bad.append(f"auditor-config keys: {sorted(cm['data'])}")
    else:
        cfg = tomllib.loads(cm["data"]["rd-dfabi.toml"])
        want_cfg = {"chain": chain, "network_id_file": "/genesis/genesis.expected_hash", "peers_json": "/config/peers.json", "key_dir": "/keys", "party": party}
        for k, v in want_cfg.items():
            if cfg.get(k) != v:
                bad.append(f"rd-dfabi.toml {k} = {cfg.get(k)!r}, want {v!r}")
        a = cfg.get("auditor", {})
        if a.get("key_name") != key_name or a.get("listen") != "0.0.0.0:8090" or a.get("store_dir") != "/audit-store":
            bad.append(f"[auditor] key_name/listen/store_dir: {a}")
        if len(a.get("parties", [])) != 4 or not all(p.startswith("ed0120") for p in a.get("parties", [])):
            bad.append("[auditor] parties must be the 4 trading accounts (ed0120 public keys), bi-gov excluded")
        if "seed" in json.dumps(cfg).lower() and "private" in json.dumps(cfg).lower():
            bad.append("the config must hold public values only")
        if sorted(cfg.get("torii", {})) != ["bank-a", "bank-b", "bank-c", "bi"]:
            bad.append(f"torii map: {cfg.get('torii')}")
        if gwtls:  # four DISTINCT loopback URLs ending in '/', one per party, served by the sidecar (upstream private_settlement.rs:330-358)
            want_t = {q: f"http://127.0.0.1:{18101 + i}/" for i, q in enumerate(("bi", "bank-a", "bank-b", "bank-c"))}
            if cfg.get("torii") != want_t:
                bad.append(f"--gw-tls: [torii] must map each party to its loopback listener {want_t}: {cfg.get('torii')}")

pvc = need("PersistentVolumeClaim", "audit-store")
if pvc and (pvc["spec"]["resources"]["requests"]["storage"] != "1Gi" or pvc["spec"]["accessModes"] != ["ReadWriteOnce"]):
    bad.append("PVC audit-store: 1Gi ReadWriteOnce")

dep = need("Deployment", "auditor")
if dep:
    s = dep["spec"]
    pod = s["template"]["spec"]
    c = pod["containers"][0]
    role = {"app.kubernetes.io/part-of": "rd-iroha3", "rd-iroha3/party": party, "rd-iroha3/role": "auditor"}
    checks = {
        "digest-pinned image": c["image"] == f"ghcr.io/radityaaa43/iroha3-rd-driver@{digest}",
        "replicas 1 + Recreate (RWO volume, one approver at a time)": s["replicas"] == 1 and s["strategy"] == {"type": "Recreate"},
        "args auditor": c["args"] == ["auditor", "/config/rd-dfabi.toml"],
        "port 8090": [p["containerPort"] for p in c["ports"]] == [8090],
        "role labels (+ rd/egress-locked on the pod template: allow-all-egress baselines skip locked pods; the selector stays role only)": s["template"]["metadata"]["labels"] == {**role, "rd/egress-locked": "true"} and s["selector"]["matchLabels"] == role,
        "no token": pod["automountServiceAccountToken"] is False,
        "non-root": pod["securityContext"].get("runAsNonRoot") is True and pod["securityContext"].get("runAsUser") == 1001,
        "container hardening": c["securityContext"].get("allowPrivilegeEscalation") is False
        and c["securityContext"].get("readOnlyRootFilesystem") is True
        and c["securityContext"].get("capabilities", {}).get("drop") == ["ALL"],
        "requests and limits": "requests" in c["resources"] and "limits" in c["resources"],
        "imagePullSecret ghcr-pull": pod.get("imagePullSecrets") == [{"name": "ghcr-pull"}],
    }
    for name, good in checks.items():
        if not good:
            bad.append(f"Deployment auditor: {name}")
    secret_vols = [v for v in pod["volumes"] if "secret" in v and v["name"] != "client-cert"]
    if pvcmode:
        # keys generated in the pod's namespace by the D5 driver image itself: never a Secret, ConfigMap, env or argv value
        if secret_vols:
            bad.append(f"--keys-in-pvc: no Secret volume at all (the key lives only on the audit-store PVC): {secret_vols}")
        if c.get("env") or c.get("envFrom"):
            bad.append("--keys-in-pvc: no env on the auditor container (no key material in env)")
        ics = pod.get("initContainers", [])
        if len(ics) != 1 or ics[0].get("name") != "keys":
            bad.append(f"--keys-in-pvc: exactly one initContainer `keys`: {[i.get('name') for i in ics]}")
        else:
            ic = ics[0]
            ics_ok = {
                "same digest-pinned driver image": ic.get("image") == c["image"] and ic["image"].endswith("@" + digest),
                "mounts only the PVC at /state": ic.get("volumeMounts") == [{"name": "state", "mountPath": "/state"}],
                "no env / ports / args": not ic.get("env") and not ic.get("ports") and not ic.get("args") and not ic.get("envFrom"),
                "hardening": ic["securityContext"].get("allowPrivilegeEscalation") is False and ic["securityContext"].get("readOnlyRootFilesystem") is True
                and ic["securityContext"].get("capabilities", {}).get("drop") == ["ALL"],
                "requests and limits": "requests" in ic.get("resources", {}) and "limits" in ic.get("resources", {}),
                "command is /bin/sh -c": ic.get("command", [])[:2] == ["/bin/sh", "-c"] and len(ic.get("command", [])) == 3,
            }
            for name, good in ics_ok.items():
                if not good:
                    bad.append(f"initContainer keys: {name}")
            sc = ic.get("command", ["", "", ""])[-1]
            for need_s in ("set -eu", "umask 077", f'keys new "$D" "$N"', f'keys new-hybrid "$D" "$N"', "chmod 0400", "keys present", "exit 1"):
                if need_s not in sc:
                    bad.append(f"initContainer keys script lacks {need_s!r}")
            for banned in ("rm ", "rm\t", "--force", "cat ", "base64", "kubectl", "curl", "wget", "tee ", "> \"$s\"", "> \"$h\"", "echo \"$(cat", "xxd", " od ", "\nod "):
                if banned in sc:
                    bad.append(f"initContainer keys script must not contain {banned!r}")
        pvc_vols = [v for v in pod["volumes"] if "persistentVolumeClaim" in v]
        if [v["persistentVolumeClaim"]["claimName"] for v in pvc_vols] != ["audit-store"] or pvc_vols[0]["name"] != "state":
            bad.append(f"--keys-in-pvc: the single PVC volume `state` must be audit-store: {pvc_vols}")
    elif len(secret_vols) != 1 or secret_vols[0]["secret"]["secretName"] != f"{key_name}-key":
        bad.append(f"the only Secret volume must be {key_name}-key (the org's OWN auditor key): {secret_vols}")
    else:
        sv = secret_vols[0]["secret"]
        if sorted(i["key"] for i in sv.get("items", [])) != sorted([f"{key_name}.seed", f"{key_name}.hybrid"]) or sv.get("defaultMode") != 0o400:
            bad.append(f"{key_name}-key must project exactly {key_name}.seed and {key_name}.hybrid with mode 0400: {sv}")
    mounts = {m["mountPath"]: m for m in c["volumeMounts"]}
    for path in ("/keys", "/config", "/genesis"):
        if path not in mounts or mounts[path].get("readOnly") is not True:
            bad.append(f"mount {path} must be read-only")
    if "/audit-store" not in mounts or mounts["/audit-store"].get("readOnly"):
        bad.append("/audit-store must be writable")
    if pvcmode:
        if mounts.get("/keys", {}).get("subPath") != "keys" or mounts.get("/keys", {}).get("name") != "state":
            bad.append(f"--keys-in-pvc: /keys must be the PVC subPath keys: {mounts.get('/keys')}")
        if mounts.get("/audit-store", {}).get("subPath") != "store" or mounts.get("/audit-store", {}).get("name") != "state":
            bad.append(f"--keys-in-pvc: /audit-store must be the PVC subPath store: {mounts.get('/audit-store')}")

if gwtls:
    dep = need("Deployment", "auditor")
    pod = dep["spec"]["template"]["spec"] if dep else {"containers": [], "volumes": []}
    names = [x["name"] for x in pod["containers"]]
    if names != ["auditor", "gw-tls"]:
        bad.append(f"--gw-tls: containers must be [auditor, gw-tls]: {names}")
    else:
        aud, sc = pod["containers"]
        EI = "envoyproxy/envoy@sha256:b1f389c3a6148e85e9de364cb867aa2e5802153abb37ad80f1f2241d693da32a"
        ok_sc = {
            "pinned official envoy digest": sc["image"] == EI,
            "args": sc.get("args") == ["-c", "/config/envoy.yaml", "--log-level", "warn"] and "command" not in sc,
            "no ports": not sc.get("ports"),
            "no env": not sc.get("env") and not sc.get("envFrom"),
            "hardening": sc["securityContext"].get("allowPrivilegeEscalation") is False and sc["securityContext"].get("readOnlyRootFilesystem") is True
            and sc["securityContext"].get("capabilities", {}).get("drop") == ["ALL"],
            "requests and limits": "requests" in sc.get("resources", {}) and "limits" in sc.get("resources", {}),
            "mounts": sorted((m["name"], m["mountPath"], bool(m.get("readOnly"))) for m in sc["volumeMounts"]) ==
            sorted([("envoy-config", "/config", True), ("server-cas", "/server-cas", True), ("client-cert", "/client", True), ("tmp", "/tmp", False)]),
        }
        for n, good in ok_sc.items():
            if not good:
                bad.append(f"sidecar gw-tls: {n}")
        if any(m["name"] == "client-cert" for m in aud["volumeMounts"]):
            bad.append("the client key must be mounted ONLY into gw-tls, not into the auditor container")
        cvol = [v for v in pod["volumes"] if v["name"] == "client-cert"]
        if len(cvol) != 1 or cvol[0].get("secret", {}).get("secretName") != "auditor-client-cert" or cvol[0]["secret"].get("defaultMode") != 0o400:
            bad.append(f"--gw-tls: volume client-cert = Secret auditor-client-cert mode 0400 (created in-namespace, not rendered): {cvol}")
    sas = need("ConfigMap", "auditor-server-cas")
    if sas and (sorted(sas["data"]) != sorted(f"{q}-server-ca.pem" for q in ("bi", "bank-a", "bank-b", "bank-c")) or any("PRIVATE KEY" in v or "BEGIN CERTIFICATE" not in v for v in sas["data"].values())):
        bad.append("auditor-server-cas must hold exactly the 4 public <party>-server-ca.pem certificates")
    ev = need("ConfigMap", "auditor-gw-envoy")
    if ev and list(ev["data"]) == ["envoy.yaml"]:
        env = yaml.safe_load(ev["data"]["envoy.yaml"])
        if "admin" in env:
            bad.append("the sidecar has no admin interface")
        ls = env["static_resources"]["listeners"]
        got = [(l["address"]["socket_address"]["address"], l["address"]["socket_address"]["port_value"]) for l in ls]
        want_l = [("127.0.0.1", 18101 + i) for i in range(4)]
        if got != want_l:
            bad.append(f"sidecar listeners must be 127.0.0.1 ONLY on 18101-18104: {got}")
        if "0.0.0.0" in ev["data"]["envoy.yaml"]:
            bad.append("the rendered sidecar config must never contain 0.0.0.0")
        cls = {c["name"]: c for c in env["static_resources"]["clusters"]}
        for i, q in enumerate(("bi", "bank-a", "bank-b", "bank-c")):
            fc = ls[i]["filter_chains"][0]["filters"][0]["typed_config"]
            route = fc["route_config"]["virtual_hosts"][0]["routes"]
            if len(route) != 1 or route[0]["route"]["cluster"] != f"gw-{q}" or route[0]["match"] != {"prefix": "/"}:
                bad.append(f"listener {18101 + i}: one route / -> cluster gw-{q}: {route}")
            if route and route[0]["route"].get("timeout") != "130s":
                bad.append(f"listener {18101 + i}: route timeout 130s (the 120 s approval path): {route[0]['route'].get('timeout')}")
            c = cls.get(f"gw-{q}")
            if not c:
                bad.append(f"missing cluster gw-{q}")
                continue
            sa = c["load_assignment"]["endpoints"][0]["lb_endpoints"][0]["endpoint"]["address"]["socket_address"]
            host = f"gateway.rd-iroha3-{q}.svc.cluster.local"
            if q == "bank-c" and party != "bank-c":
                if c.get("type") != "STATIC" or sa != {"address": bankc_ip, "port_value": 8443}:
                    bad.append(f"cluster gw-bank-c: STATIC {bankc_ip}:8443 (the other cluster's gateway-lb /32): {c.get('type')} {sa}")
            elif c.get("type") != "STRICT_DNS" or sa != {"address": host, "port_value": 8443}:
                bad.append(f"cluster gw-{q}: STRICT_DNS {host}:8443: {c.get('type')} {sa}")
            tc = c.get("transport_socket", {}).get("typed_config", {})
            cc = tc.get("common_tls_context", {})
            vc = cc.get("validation_context", {})
            good_tls = (tc.get("@type", "").endswith("UpstreamTlsContext") and tc.get("sni") == host
                        and cc.get("tls_params") == {"tls_minimum_protocol_version": "TLSv1_2"}
                        and cc.get("tls_certificates") == [{"certificate_chain": {"filename": "/client/tls.crt"}, "private_key": {"filename": "/client/tls.key"}}]
                        and vc.get("trusted_ca") == {"filename": f"/server-cas/{q}-server-ca.pem"}
                        and vc.get("match_typed_subject_alt_names") == [{"san_type": "DNS", "matcher": {"exact": host}}]
                        and "trust_chain_verification" not in vc and "verify_certificate_hash" not in vc and "verify_certificate_spki" not in vc)
            if not good_tls:
                bad.append(f"cluster gw-{q}: upstream mTLS must pin ONLY {q}'s server CA, match SAN {host}, present the client leaf, TLS >= 1.2, no skip-verify: {json.dumps(tc)[:300]}")

        # analyst ruling 6(b)(ii): the committee has 4 DISTINCT endpoints, one per party, in roster order bi, bank-a, bank-b, bank-c (upstream private_settlement.rs:345-377)
        tor = {}
        cfgm = need("ConfigMap", "auditor-config")
        if cfgm:
            tor = tomllib.loads(cfgm["data"]["rd-dfabi.toml"]).get("torii", {})
        urls = [tor.get(q) for q in ("bi", "bank-a", "bank-b", "bank-c")]
        cas = [c.get("transport_socket", {}).get("typed_config", {}).get("common_tls_context", {}).get("validation_context", {}).get("trusted_ca", {}).get("filename") for c in (cls.get(f"gw-{q}", {}) for q in ("bi", "bank-a", "bank-b", "bank-c"))]
        if len(set(urls)) != 4 or None in urls or len(set(cas)) != 4 or None in cas or len(set(got)) != 4:
            bad.append(f"--gw-tls: 4 DISTINCT endpoints (urls {urls}), 4 distinct server-CA pins ({cas}), 4 distinct listeners ({got}), in roster order")

svc = need("Service", "auditor")
if svc and (svc["spec"]["type"] != "ClusterIP" or svc["spec"]["ports"][0]["port"] != 8090):
    bad.append("Service auditor: ClusterIP 8090")

np = need("NetworkPolicy", "auditor-ingress")
if np:
    if np["spec"]["podSelector"] != {"matchLabels": {"rd-iroha3/role": "auditor"}} or np["spec"]["policyTypes"] != ["Ingress"]:
        bad.append("NetworkPolicy auditor-ingress: selector role=auditor, Ingress only")
    if np["spec"]["ingress"] != [{"from": [{"podSelector": {"matchLabels": {"rd-iroha3/role": "gateway"}}}], "ports": [{"protocol": "TCP", "port": 8090}]}]:
        bad.append(f"NetworkPolicy auditor-ingress: TCP 8090 from the own gateway pods ONLY: {np['spec']['ingress']}")

# R17 precondition of the apply: the key-holding auditor gets its own narrow Egress policy (DNS + its own party's Torii; approvals arrive INBOUND
# through the gateway, so no cross-party or internet egress).
eg = need("NetworkPolicy", "auditor-egress")
if eg:
    sp = eg["spec"]
    want_eg = [
        {"to": [{"namespaceSelector": {"matchLabels": {"kubernetes.io/metadata.name": "kube-system"}},
                 "podSelector": {"matchLabels": {"k8s-app": "kube-dns"}}}],
         "ports": [{"protocol": "UDP", "port": 53}, {"protocol": "TCP", "port": 53}]},
        {"to": [{"podSelector": {"matchLabels": {"rd-iroha3/role": "peer", "rd-iroha3/party": party}}}], "ports": [{"protocol": "TCP", "port": 8080}]},
    ]
    if sp.get("podSelector") != {"matchLabels": {"rd-iroha3/role": "auditor", "rd/egress-locked": "true"}} or sp.get("policyTypes") != ["Egress"] or "ingress" in sp:
        bad.append(f"NetworkPolicy auditor-egress: selector role=auditor + rd/egress-locked=true, Egress only: {sp.get('podSelector')} {sp.get('policyTypes')}")
    if gwtls:  # DNS + the 4 gateways :8443 (cluster 1 by ns+role selector, bank-c's gateway-lb by /32), NO Torii
        want_eg = [want_eg[0], {"to": [{"namespaceSelector": {"matchLabels": {"kubernetes.io/metadata.name": f"rd-iroha3-{q}"}}, "podSelector": {"matchLabels": {"rd-iroha3/role": "gateway"}}}
                                       for q in ("bi", "bank-a", "bank-b")] + [{"ipBlock": {"cidr": f"{bankc_ip}/32"}}], "ports": [{"protocol": "TCP", "port": 8443}]}]
        if sp.get("egress") != want_eg:
            bad.append(f"NetworkPolicy auditor-egress (--gw-tls): DNS + 4 gateways :8443, NO Torii: {json.dumps(sp.get('egress'))}")
        if "8080" in json.dumps(sp):
            bad.append("NetworkPolicy auditor-egress (--gw-tls): no Torii (8080)")
    else:
        if sp.get("egress") != want_eg:
            bad.append(f"NetworkPolicy auditor-egress: only DNS + own Torii 8080: {json.dumps(sp.get('egress'))}")
        if "ipBlock" in json.dumps(sp):
            bad.append("NetworkPolicy auditor-egress: no ipBlock")

if bad:
    print("\n".join(f"FAIL: {party}: {b}" for b in bad), file=sys.stderr)
    sys.exit(1)
print(f"ok:   {party}: {len(docs)} objects match")
